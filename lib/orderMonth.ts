const MONTHS = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"];

// Месяц для плашки «беру заказы на …»: после 20 числа — уже следующий.
// После «на» нужен винительный падеж — у названий месяцев он совпадает с обычной формой.
export function orderMonth(date = new Date()) {
  const m = date.getDate() > 20 ? (date.getMonth() + 1) % 12 : date.getMonth();
  return MONTHS[m];
}
